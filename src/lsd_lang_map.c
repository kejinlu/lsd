static const size_t lsd_lang_map_size = sizeof(lsd_lang_map) / sizeof(lsd_lang_map[0]);

const char *lsd_lang_lookup_bcp47(uint16_t lcid) {
    size_t lo = 0;
    size_t hi = lsd_lang_map_size;

    while (lo < hi) {
        size_t mid = lo + (hi - lo) / 2;
        if (lsd_lang_map[mid].lcid < lcid) {
            lo = mid + 1;
        } else if (lsd_lang_map[mid].lcid > lcid) {
            hi = mid;
        } else {
            return lsd_lang_map[mid].bcp47;
        }
    }

    return NULL;
}
